# Student name variable
student_name = "Ali"
# Student score variable
student_score = 90
# Condition
#   Check 90 for A
#   Check 80 for B
#   Check 70 for C
#   Else statement for F
if student_score >= 90:
    print(student_name + " has an A grade")
elif student_score >= 80:
    print(student_name + " has a B grade")
elif student_score >= 70:
    print(student_name + " has a C grade")
else:
    print(student_name + " has an F grade")
# Output the grade with a print statement